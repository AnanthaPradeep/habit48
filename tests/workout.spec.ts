import { devices, expect, test, type Page } from '@playwright/test'
import { ownerUsername } from '../src/services/config'
import { journalBackend } from './supabase-fixture'

async function open(page: Page) {
  await page.goto('./')
  await page.locator('#splash').waitFor({ state: 'hidden' })
  await page.getByLabel('Email address').fill(ownerUsername)
  await page.getByLabel('Password', { exact: true }).fill('sample-password')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Workout' }).click()
  await expect(page.getByRole('heading', { name: 'Move with purpose.' })).toBeVisible()
  await expect(page.getByText('Workouts synced', { exact: true })).toBeVisible()
}

test('plays form demos, runs an offline workout and syncs completed sets and plans across devices',
  async ({ page: desktop, browser, context, baseURL }, info) => {
    test.skip(info.project.name !== 'desktop', 'This test creates a separate phone context.')
    const backend = journalBackend()
    await backend.attach(context)
    const phoneContext = await browser.newContext({ ...devices['Pixel 7'], baseURL })
    try {
      const phoneBackend = await backend.attach(phoneContext)
      const phone = await phoneContext.newPage()
      await Promise.all([open(desktop), open(phone)])
      await expect(phone.getByText('40 exercises', { exact: true })).toBeVisible()
      await expect(phone.locator('.studio-exercise')).toHaveCount(12)
      const exercisePages = phone.getByRole('navigation', { name: 'Exercise pages' })
      await exercisePages.getByRole('button', { name: 'Next page' }).click()
      await expect(exercisePages.getByRole('status')).toContainText('Page 2 of 4')
      await phone.getByLabel('Search exercises').fill('biceps')
      await expect(phone.locator('.studio-exercise')).toHaveCount(1)
      await phone.locator('.studio-exercise').click()
      const details = phone.getByRole('region', { name: 'Exercise details' })
      const art = details.getByRole('img')
      const previous = await art.evaluate(node => (node as HTMLCanvasElement).toDataURL())
      await details.getByRole('button', { name: 'Play demo' }).click()
      await expect.poll(() => art.evaluate(node => (node as HTMLCanvasElement).toDataURL())).not.toBe(previous)
      await details.getByRole('button', { name: 'Pause demo' }).click()

      await desktop.getByRole('button', { name: 'Custom workout', exact: true }).click()
      await desktop.getByLabel('Workout name').fill('Home session')
      await desktop.getByRole('button', { name: 'Add exercise', exact: true }).click()
      await desktop.getByRole('button', { name: 'Save custom workout' }).click()
      await expect(phone.getByRole('button', { name: /Home session/ })).toBeVisible()
      await phone.getByRole('button', { name: /Home session/ }).click()
      await phone.getByRole('button', { name: 'Start workout' }).click()
      await expect(phone.getByRole('dialog', { name: 'Workout player' })).toBeVisible()
      let guide = phone.getByRole('region', { name: 'Guided workout' })
      await guide.getByRole('button', { name: 'Complete set 1' }).click()
      await expect(guide.getByText(/Rest · \d+:\d+/)).toBeVisible()
      await guide.getByRole('button', { name: 'Pause', exact: true }).click()
      await expect(guide.getByRole('button', { name: 'Complete set 2' })).toBeDisabled()
      const desktopGuide = desktop.getByRole('region', { name: 'Guided workout' })
      await expect(desktopGuide.getByText(/1\/2 sets/)).toBeVisible()
      await expect(desktopGuide.getByRole('button', { name: 'Resume', exact: true })).toBeVisible()
      await phone.waitForFunction(() => Boolean(navigator.serviceWorker.controller))
      phoneBackend.offline(true)
      await phoneContext.setOffline(true)
      await phone.reload()
      await phone.locator('#splash').waitFor({ state: 'hidden' })
      guide = phone.getByRole('region', { name: 'Guided workout' })
      await expect(guide.getByText(/1\/2 sets/)).toBeVisible()
      await guide.getByRole('button', { name: 'Resume' }).click()
      await guide.getByRole('button', { name: 'Skip rest' }).click()
      await guide.getByRole('button', { name: 'Complete set 2' }).click()
      await guide.getByRole('button', { name: 'Finish workout' }).click()
      await expect(phone.getByRole('region', { name: 'Workout completion summary' })).toContainText('2 sets')
      await expect(phone.locator('.workout-record')).toHaveCount(1)
      expect(backend.workouts()).toHaveLength(0)
      phoneBackend.offline(false)
      await phoneContext.setOffline(false)
      await expect(desktop.locator('.workout-record')).toContainText('Home session')
      await expect.poll(() => backend.workouts()[0]?.sets.length).toBe(2)
      await desktop.getByRole('navigation').getByRole('link', { name: 'Journal', exact: true }).click()
      await expect(desktop.getByRole('region', { name: 'Workout Studio summary' })).toContainText('2 sets')
    } finally { await phoneContext.close() }
  })
